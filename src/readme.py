"""Render README.md from docs/README.template.md: `python -m src.readme`.

Every `{{key}}` placeholder is replaced by the `display` text of that key in
outputs/numbers_for_note.json (`{{verdict_sentence}}` by its top-level verdict).
Unknown keys are an error, so the README can only quote recorded numbers.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TEMPLATE_PATH = ROOT / "docs" / "README.template.md"
NUMBERS_PATH = ROOT / "outputs" / "numbers_for_note.json"
PROVENANCE_PATH = ROOT / "data" / "processed" / "provenance.json"
README_PATH = ROOT / "README.md"
PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_]+)\s*\}\}")
TEMPLATE_COMMENT = re.compile(r"\A<!--.*?-->\n", re.S)


def provenance_values(provenance: dict | None) -> dict[str, str]:
    """Placeholders generated by `python run.py facts` (data/processed/provenance.json)."""
    limitation = (provenance or {}).get("release_lag_limitation", {})
    return {"lag_look_ahead_sentence": limitation.get(
        "look_ahead_sentence", "Look-ahead status: UNKNOWN (run `python run.py facts`).")}


def render(template: str, numbers: dict, provenance: dict | None = None) -> str:
    values = {key: entry["display"] for key, entry in numbers["numbers"].items()}
    values["verdict_sentence"] = numbers["verdict_sentence"]
    values |= provenance_values(provenance)
    body = TEMPLATE_COMMENT.sub("", template)
    missing = sorted({key for key in PLACEHOLDER.findall(body) if key not in values})
    if missing:
        raise KeyError(f"README template uses keys missing from numbers_for_note.json: {missing}")
    header = "<!-- Generated by `python run.py report` from docs/README.template.md; do not edit by hand. -->\n"
    return header + PLACEHOLDER.sub(lambda match: values[match.group(1)], body)


def build(numbers_path: Path = NUMBERS_PATH, template_path: Path = TEMPLATE_PATH,
          provenance_path: Path = PROVENANCE_PATH) -> str:
    numbers = json.loads(Path(numbers_path).read_text(encoding="utf-8"))
    provenance = (json.loads(Path(provenance_path).read_text(encoding="utf-8"))
                  if Path(provenance_path).is_file() else None)
    return render(Path(template_path).read_text(encoding="utf-8"), numbers, provenance)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render README.md from the template and the note's numbers.")
    parser.add_argument("--numbers", type=Path, default=NUMBERS_PATH)
    parser.add_argument("--output", type=Path, default=README_PATH)
    args = parser.parse_args(argv)
    args.output.write_text(build(args.numbers), encoding="utf-8", newline="\n")
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
